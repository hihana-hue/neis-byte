import assert from 'node:assert/strict';
import fs from 'node:fs';
import vm from 'node:vm';
import {lessonRounds} from './academy-model.mjs';
const ctx=vm.createContext({});
vm.runInContext(fs.readFileSync(new URL('./server/worker.mjs',import.meta.url),'utf8').split('function rpPushError')[0]+';this.rounds=rpLessonRounds;',ctx);
const row=(id,start,extra={})=>({id,kind:'과학',subtype:'정규',status:'예정',start,...extra});
const check=(rows,expected)=>{for(const fn of [lessonRounds,ctx.rounds]){const actual=fn(rows);for(const [id,label] of Object.entries(expected))assert.equal(actual.get(id),label,id);}};
const old=row('old','2026-10-02',{status:'출석'});
const anchor=row('anchor','2026-10-25',{roundAnchor:true,status:'출석'});
const next=row('next','2026-11-01');
check([next,old,anchor],{next:'2/4'});
check([next,anchor],{next:'2/4'});
check([old,anchor,next,row('clinic','2026-10-28',{subtype:'클리닉'}),row('skip','2026-10-29',{status:'결석'}),row('paid','2026-10-30',{status:'결석',charge:true})],{next:'3/4',clinic:'클리닉'});
check([anchor,{...next,start:'2026-10-24',originalStart:'2026-11-01'}],{next:'2/4'});
check([anchor,next,row('two','2026-11-08'),row('three','2026-11-15'),row('four','2026-11-22')],{next:'2/4',two:'3/4',three:'4/4',four:'1/4'});
check([anchor,next,row('pt','2026-11-01',{kind:'바디PT',roundAnchor:true})],{next:'2/4',pt:'1/5'});
check([anchor,{...next,roundAnchor:true}],{next:'기준 확인'});
check([{...anchor,status:'결석'},next],{next:'기준 확인'});
check([{...anchor,subtype:'클리닉'},next],{next:'기준 확인'});
check([old,next],{next:'2/4'});
console.log('Web and widget anchor parity checks passed');
